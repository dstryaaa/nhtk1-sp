package discounts

import "testing"

func TestRoundToHalfEven(t *testing.T) {
	tests := []struct {
		name string
		a, b int64
		want int64
	}{
		// Точные значения — без округления.
		{"точно 2", 200, 100, 2},
		{"точно 0", 0, 100, 0},

		// Half-to-even: ровно половина → к чётному.
		{"2.5 → 2", 250, 100, 2}, // 2 чётное
		{"3.5 → 4", 350, 100, 4}, // 4 чётное (3 нечётное → вверх)
		{"0.5 → 0", 50, 100, 0},  // 0 чётное
		{"1.5 → 2", 150, 100, 2}, // 2 чётное (1 нечётное → вверх)
		{"2.5 (b=10) → 2", 25, 10, 2},
		{"3.5 (b=10) → 4", 35, 10, 4},

		// Не половина — обычное округление.
		{"2.4 → 2", 240, 100, 2},
		{"2.6 → 3", 260, 100, 3},
		{"0.4 → 0", 40, 100, 0},
		{"0.6 → 1", 60, 100, 1},

		// Делитель не 100.
		{"10/3 = 3.33 → 3", 10, 3, 3},
		{"11/3 = 3.67 → 4", 11, 3, 4},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := roundToHalfEven(tt.a, tt.b)
			if got != tt.want {
				t.Errorf("roundToHalfEven(%d, %d) = %d, want %d", tt.a, tt.b, got, tt.want)
			}
		})
	}
}
